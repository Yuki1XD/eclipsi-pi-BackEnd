    patient_id bigint primary key references public.users(id) on delete cascade,
    motivo_principal text not null,
    abordagem_preferida text not null,
    modalidade text not null,
    faixa_valor_max numeric(10, 2) not null check (faixa_valor_max > 0),
    urgencia text not null,
    atualizado_em timestamptz not null default now()
);

create table if not exists public.pagamentos (
    id bigint generated by default as identity primary key,
    consulta_id bigint not null references public.consultas(id),
    valor numeric(10, 2) not null,
    metodo text not null,
    status text not null default 'pendente',
    codigo_pix text
);

